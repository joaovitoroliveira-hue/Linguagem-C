#include <stdio.h>
int main(){
    int idade;
    printf("Digite sua idade: ");
    scanf("%d", &idade);
    return(0);
}
/*

  * int idade: Variável do tipo int e com nome idade.

  * scanf: Permite escrever na tela.

  * %d: Formatação para ler inteiro.

  * &: Operador de endereço (indica onde vai ser armazenado algum valor).

*/