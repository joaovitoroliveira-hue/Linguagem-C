#include <stdio.h>
int main(){
    printf("Hello World!\n");
    return(0);
}
/*
- Este é o código mais básico da Linguagem C, o famoso "Hello World". Em apenas 5 linhas de código reunimos muitas coisas
  importantes por aqui.
  * #include <stdio.h>: Diretrizes de pré-processador que importa bibliotecas de I/O padrão.
  
  * int main(): Função principal (ponto de partida obrigatório de qualquer programa em C).

  * printf(): Função que exibe dados na tela. "\n" é um escape sequence que faz quebra de linha após a mensagem.

  * return(0): 
*/