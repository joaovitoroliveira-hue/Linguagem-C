#include <stdio.h>

int main() {
    int idades[5];      // Array com 5 posições que guardam valores inteiros
    float notas[30];    // Array com 30 posições que guardam valores reais
    char letras[10];    // Array com 10 posições que guardam valores caractere
    double precos[100]; // Array com 100 posições que guardam valores reais com dupla precisão

    return(0);
}
/*

- Sintaxe Geral: tipo nome_do_array[tamanho]

- Tipo: Irá definir o tipo de cada elemento guardado dentro do array (int, float, char...)

- Nome: Identificador do array, seguindo as mesmas regras de nomeação para qualquer variável

- Tamanho: Número fixo de elementos. Deve ser um valor inteiro positivo, preferencialmente uma constante

*/